/* global document */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5173');
  await page.waitForFunction(() => document.documentElement.dataset.viewerReady === 'true');
  await page.waitForFunction(() => document.documentElement.dataset.initializationReady === 'true');
  assert.equal(await page.locator('canvas').count(), 1);
  const readOutput = async () => JSON.parse(await page.locator('#initial-state').innerText());
  const initial = await readOutput();
  assert.equal(initial.state.phase, 'grid');
  assert.equal(Object.keys(initial.state.ruStates).length, 6);
  assert.equal(initial.state.ruStates['ru-player'].tile.segmentId, 'seg-00');
  await page.getByText('Edit scenario and content JSON', { exact: true }).click();
  const original = await page.locator('#scenario-json').inputValue();
  const originalContent = await page.locator('#content-json').inputValue();
  const changedContent = JSON.parse(originalContent);
  changedContent.drivers.find(driver => driver.id === 'driver-player').currentHealth = 40;
  await page.locator('#content-json').fill(JSON.stringify(changedContent));
  const changed = JSON.parse(original);
  changed.seed = 'browser-reinitialization';
  await page.locator('#scenario-json').fill(JSON.stringify(changed));
  await page.locator('#initialize').click();
  const next = await readOutput();
  assert.equal(next.state.seed, changed.seed);
  assert.equal(next.state.ruStates['ru-player'].driver.band, 'critical');
  assert.notDeepEqual(next.state.rngStates, initial.state.rngStates);
  changed.startingGrid['ru-player'].lane = 12;
  await page.locator('#scenario-json').fill(JSON.stringify(changed));
  await page.locator('#initialize').click();
  assert.match(await page.locator('#setup-feedback').innerText(), /scenario.startingGrid.ru-player/);
  assert.equal(await page.locator('#initial-state').innerText(), '');
  await page.locator('#scenario-json').fill(original);
  await page.locator('#content-json').fill(JSON.stringify(JSON.parse(originalContent))); // Same data, avoiding a huge multiline keyboard insertion.
  await page.locator('#initialize').click();
  assert.deepEqual((await readOutput()).state, initial.state);
  await page.locator('#step-tick').click();
  const tickOne = await readOutput();
  assert.equal(tickOne.state.tick, 1);
  assert.equal(tickOne.state.phase, 'running');
  assert.ok(tickOne.state.ruStates['ru-player'].speedMps > 0);
  assert.ok(tickOne.state.ruStates['ru-player'].derived.breakdown.coordination > 0);
  await page.locator('#step-tick').click();
  assert.equal((await readOutput()).state.tick, 2);
  const downloading = page.waitForEvent('download');
  await page.locator('#export-diagnostics').click();
  const downloaded = await downloading;
  const bundle = JSON.parse(readFileSync(await downloaded.path(), 'utf8'));
  assert.equal(bundle.state.tick, 2);
  assert.equal(bundle.latestTick.stateHash, (await readOutput()).stateHash);
  assert.equal(bundle.initialConfiguration.scenario.seed, initial.state.seed);
  await page.locator('#load-race-sample').click();
  const raceScenario = JSON.parse(await page.locator('#scenario-json').inputValue());
  const raceContent = JSON.parse(await page.locator('#content-json').inputValue());
  raceScenario.rules.laps = 1;
  raceContent.tracks[0].segments.forEach(segment => { segment.meters = .0005; });
  await page.locator('#scenario-json').fill(JSON.stringify(raceScenario));
  await page.locator('#content-json').fill(JSON.stringify(raceContent));
  await page.locator('#initialize').click();
  assert.equal((await readOutput()).state.phase, 'grid');
  assert.equal((await readOutput()).state.ruStates['ru-bone'].normalizedCoursePosition, -1);
  await page.locator('#step-tick').click();
  let completed = await readOutput();
  for (let attempts = 0; attempts < 4 && completed.state.phase !== 'complete'; attempts++) {
    assert.notEqual(completed.state.phase, 'error');
    await page.locator('#step-tick').click();
    completed = await readOutput();
  }
  assert.equal(completed.state.phase, 'complete');
  assert.equal(completed.state.result.outcome, 'classified');
  assert.equal(completed.state.ruStates['ru-bone'].completedLaps, 1);
  assert.equal(completed.state.ruStates['ru-bone'].startLineCrossings, 2);
  assert.ok(completed.state.ruStates['ru-bone'].firstLapStartedAtSeconds > 0);
  assert.equal(completed.state.result.classification.length, 6);
  assert.ok(completed.state.result.winnerIds.length > 0);
  assert.equal(await page.locator('#step-tick').isDisabled(), true);
  const raceDownloading = page.waitForEvent('download');
  await page.locator('#export-diagnostics').click();
  const raceBundle = JSON.parse(readFileSync(await (await raceDownloading).path(), 'utf8'));
  assert.deepEqual(raceBundle.state.result, completed.state.result);
  assert.deepEqual(errors, []);
  console.log('Phaser canvas, initialized grid, seed editing, invalid setup rejection and repeat initialization, exact tick stepping and diagnostic download and A3 six-RU results: PASS');
} finally { await browser.close(); }
